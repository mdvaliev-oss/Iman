/** Дуа для конкретной даты — циклически по номеру дня, поэтому меняется каждый день. */
export function duaForDate(dateStr) {
  const d = new Date(dateStr + "T00:00:00");
  const dayNum = Math.floor(d.getTime() / 86400000);
  const i = ((dayNum % DUAS.length) + DUAS.length) % DUAS.length;
  return DUAS[i];
}
